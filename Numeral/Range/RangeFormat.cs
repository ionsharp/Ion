namespace Ion.Numeral;

/// <summary>Defines the format of a range.</summary>
public enum RangeFormat
{
    /// <summary>Defines a range of [0, 1].</summary>
    Nominal,
    /// <summary>Defines a standard range.</summary>
    Standard,
    /// <summary>Defines a zero-based range.</summary>
    ZeroBased,
}